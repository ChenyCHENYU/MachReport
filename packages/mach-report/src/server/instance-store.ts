export interface ReportInstanceArtifact { key: string; format: "pdf" | "xlsx"; bytes: number; sha256?: string }
export interface ReportInstanceSnapshot {
  scope: string;
  id: string;
  revision: number;
  title: string;
  generatedAt: string;
  reportIds: string[];
  params: Record<string, string>;
  /** Exact template/data revisions used by generation, never inferred from a later template read. */
  templateRevisions: Record<string, string>;
  sourceRevisions: Record<string, string>;
  plan: RenderPlan;
  /** Private storage keys; signed download URLs must be generated by the host after authorization. */
  artifacts?: ReportInstanceArtifact[];
}
export type ReportInstanceSummary = Omit<ReportInstanceSnapshot, "plan" | "artifacts">;
export interface ReportInstancePage { items: ReportInstanceSummary[]; next?: string }
export interface ReportInstanceListOptions { after?: string; limit?: number; reportId?: string; signal?: AbortSignal }
export interface ReportInstanceStore {
  read(scope: string, id: string, revision?: number, signal?: AbortSignal): Promise<ReportInstanceSnapshot | undefined>;
  list(scope: string, options?: ReportInstanceListOptions): Promise<ReportInstancePage>;
  /** Atomic append + current-revision advance. Historical revisions must never be overwritten. */
  compareAndSwap(scope: string, id: string, expectedRevision: number | null, next: ReportInstanceSnapshot, signal?: AbortSignal): Promise<boolean>;
}
export class ReportInstanceError extends Error {
  constructor(readonly code: "input" | "conflict" | "capacity", message: string) { super(message); this.name = "ReportInstanceError"; }
}
export function checkInstanceIdentity(scope: string, id: string): void {
  if (typeof scope !== "string" || !scope.trim() || scope.length > 256 || typeof id !== "string" || id !== id.trim() || !/^[a-zA-Z0-9][a-zA-Z0-9_.:-]{0,127}$/.test(id)) throw new ReportInstanceError("input", "实例范围应非空，ID 应为安全标识");
}
function checkSnapshotContainer(item: object, array: boolean): void {
  const prototype = Object.getPrototypeOf(item);
  if (prototype !== (array ? Array.prototype : Object.prototype) && !(prototype === null && !array) || Object.getOwnPropertySymbols(item).length) throw new ReportInstanceError("input", "实例应为普通 JSON 对象");
  if (array && Object.keys(item).some(key => key !== String(Number(key)) || !Number.isSafeInteger(Number(key)) || Number(key) < 0 || Number(key) >= (item as unknown[]).length)) throw new ReportInstanceError("input", "实例数组不能包含额外属性");
  const names = Object.getOwnPropertyNames(item).filter(key => !(array && key === "length"));
  if (names.length !== Object.keys(item).length) throw new ReportInstanceError("input", "实例不能包含不可枚举属性");
}
function validateInstanceMetadata(snapshot: ReportInstanceSnapshot): void {
  if (!Number.isSafeInteger(snapshot.revision) || snapshot.revision < 1 || typeof snapshot.title !== "string" || !snapshot.title.trim() || snapshot.title.length > 512) throw new ReportInstanceError("input", "实例修订或标题无效");
  if (typeof snapshot.generatedAt !== "string" || !Number.isFinite(Date.parse(snapshot.generatedAt)) || new Date(snapshot.generatedAt).toISOString() !== snapshot.generatedAt) throw new ReportInstanceError("input", "实例生成时间应为 ISO UTC 字符串");
  if (!Array.isArray(snapshot.reportIds) || !snapshot.reportIds.length || snapshot.reportIds.length > 100 || snapshot.reportIds.some(id => typeof id !== "string" || !id.trim()) || new Set(snapshot.reportIds).size !== snapshot.reportIds.length) throw new ReportInstanceError("input", "实例报表 ID 应非空且唯一");
}
function snapshotScalar(value: unknown): boolean {
  return value === null || typeof value === "boolean" || typeof value === "string" || typeof value === "number" && Number.isFinite(value);
}
function plainSnapshot(value: unknown, maximum: number): string {
  if (!Number.isSafeInteger(maximum) || maximum < 1) throw new ReportInstanceError("input", "实例快照字节预算应为正安全整数");
  let nodes = 0, characters = 0;
  const ancestors = new Set<object>();
  function visit(item: unknown, depth: number): unknown {
    if (++nodes > 1_000_000 || depth > 64) throw new ReportInstanceError("capacity", "实例节点或嵌套深度超过预算");
    if (typeof item === "string") { characters += item.length; if (characters > maximum) throw new ReportInstanceError("capacity", "实例文本超过预算"); }
    if (snapshotScalar(item)) return item;
    if (!item || typeof item !== "object" || ancestors.has(item)) throw new ReportInstanceError("input", "实例只允许无循环的有限 JSON 值");
    const array = Array.isArray(item);
    checkSnapshotContainer(item, array);
    ancestors.add(item);
    const result: Record<string, unknown> = Object.create(null);
    for (const key of Object.keys(item)) {
      characters += key.length;
      if (characters > maximum) throw new ReportInstanceError("capacity", "实例文本超过预算");
      const descriptor = Object.getOwnPropertyDescriptor(item, key)!;
      if (descriptor.get || descriptor.set || ["__proto__", "constructor", "prototype"].includes(key)) throw new ReportInstanceError("input", "实例不能包含访问器或危险键");
      if (descriptor.value !== undefined) result[key] = visit(descriptor.value, depth + 1);
    }
    ancestors.delete(item);
    if (array) {
      if (Object.keys(result).length !== item.length) throw new ReportInstanceError("input", "实例数组不能稀疏或包含额外属性");
      return Array.from({ length: item.length }, (_, index) => result[String(index)]);
    }
    return result;
  }
  const text = JSON.stringify(visit(value, 0));
  if (new TextEncoder().encode(text).byteLength > maximum) throw new ReportInstanceError("capacity", "实例快照超过单条字节预算");
  return text;
}
export function snapshotReportInstance(value: ReportInstanceSnapshot, maxBytes = 8_000_000): ReportInstanceSnapshot {
  const snapshot = JSON.parse(plainSnapshot(value, maxBytes)) as ReportInstanceSnapshot;
  checkInstanceIdentity(snapshot.scope, snapshot.id);
  const keys = new Set(["scope", "id", "revision", "title", "generatedAt", "reportIds", "params", "templateRevisions", "sourceRevisions", "plan", "artifacts"]);
  if (Object.keys(snapshot).some(key => !keys.has(key))) throw new ReportInstanceError("input", "实例包含未知字段");
  validateInstanceMetadata(snapshot);
  for (const dictionary of [snapshot.params, snapshot.templateRevisions, snapshot.sourceRevisions]) {
    if (!dictionary || typeof dictionary !== "object" || Array.isArray(dictionary) || Object.values(dictionary).some(item => typeof item !== "string")) throw new ReportInstanceError("input", "实例参数和修订应为字符串字典");
  }
  if (snapshot.reportIds.some(id => !snapshot.templateRevisions[id])) throw new ReportInstanceError("input", "每张报表都应记录生成时的模板修订");
  const validation = validateRenderPlan(snapshot.plan);
  if (!validation.ok) throw new ReportInstanceError("input", `实例渲染计划无效：${validation.errors[0]?.path}`);
  if (snapshot.artifacts !== undefined) validateArtifacts(snapshot.artifacts);
  return snapshot;
}
function validateArtifacts(artifacts: ReportInstanceArtifact[]): void {
  if (!Array.isArray(artifacts) || artifacts.length > 100) throw new ReportInstanceError("input", "实例文件列表无效");
  const keys = new Set<string>();
  for (const artifact of artifacts) {
    if (!artifact || typeof artifact.key !== "string" || !artifact.key.trim() || artifact.key.length > 1024 || keys.has(artifact.key) || !["pdf", "xlsx"].includes(artifact.format) || !Number.isSafeInteger(artifact.bytes) || artifact.bytes < 0 || artifact.sha256 !== undefined && (typeof artifact.sha256 !== "string" || artifact.sha256.length !== 64 || !/^[a-f0-9]{64}$/i.test(artifact.sha256))) throw new ReportInstanceError("input", "实例文件应包含唯一存储键、格式、大小和可选 SHA256");
    keys.add(artifact.key);
  }
}
export function reportInstanceSummary(snapshot: ReportInstanceSnapshot): ReportInstanceSummary {
  const { scope, id, revision, title, generatedAt, reportIds, params, templateRevisions, sourceRevisions } = snapshot;
  return JSON.parse(JSON.stringify({ scope, id, revision, title, generatedAt, reportIds, params, templateRevisions, sourceRevisions })) as ReportInstanceSummary;
}
export interface MemoryReportInstanceStoreOptions { maxInstances?: number; maxRevisions?: number; maxBytes?: number; maxSnapshotBytes?: number }
function instanceBudget(options: MemoryReportInstanceStoreOptions): Required<MemoryReportInstanceStoreOptions> {
  const values = { maxInstances: 100, maxRevisions: 20, maxBytes: 64_000_000, maxSnapshotBytes: 8_000_000, ...options };
  if (Object.values(values).some(value => !Number.isSafeInteger(value) || value < 1)) throw new ReportInstanceError("input", "实例存储预算应为正安全整数");
  return values;
}
/** Bounded reference store for tests/local sessions. Production hosts implement durable transactional CAS. */
export function createMemoryReportInstanceStore(options: MemoryReportInstanceStoreOptions = {}): ReportInstanceStore {
  const budget = instanceBudget(options), entries = new Map<string, Map<number, ReportInstanceSnapshot>>();
  let bytes = 0;
  return {
    read: async (scope, id, revision, signal) => {
      throwIfAborted(signal); checkInstanceIdentity(scope, id);
      const history = entries.get(JSON.stringify([scope, id])), current = history?.get(revision ?? history.size);
      return current ? snapshotReportInstance(current, budget.maxSnapshotBytes) : undefined;
    },
    list: async (scope, request = {}) => {
      throwIfAborted(request.signal); checkInstanceIdentity(scope, "list");
      const limit = request.limit ?? 25;
      if (!Number.isSafeInteger(limit) || limit < 1 || limit > 100) throw new ReportInstanceError("input", "实例每页数量应为 1–100");
      const items = Array.from(entries.values(), history => history.get(history.size)!).filter(item => item.scope === scope && (!request.after || item.id > request.after) && (!request.reportId || item.reportIds.includes(request.reportId))).sort((a, b) => a.id < b.id ? -1 : 1).slice(0, limit + 1);
      return { items: items.slice(0, limit).map(reportInstanceSummary), ...(items.length > limit ? { next: items[limit - 1]!.id } : {}) };
    },
    compareAndSwap: async (scope, id, expected, value, signal) => {
      throwIfAborted(signal); checkInstanceIdentity(scope, id);
      const next = snapshotReportInstance(value, budget.maxSnapshotBytes);
      if (next.scope !== scope || next.id !== id || next.revision !== (expected ?? 0) + 1) throw new ReportInstanceError("input", "实例身份或修订不一致");
      const key = JSON.stringify([scope, id]), history = entries.get(key) ?? new Map<number, ReportInstanceSnapshot>();
      if ((history.size || null) !== expected) return false;
      const size = new TextEncoder().encode(JSON.stringify(next)).byteLength;
      if (history.size >= budget.maxRevisions || bytes + size > budget.maxBytes || !history.size && entries.size >= budget.maxInstances) throw new ReportInstanceError("capacity", "实例存储达到预算，请使用持久化归档策略或显式调整容量");
      history.set(next.revision, next); entries.set(key, history); bytes += size; return true;
    }
  };
}
/** Save is explicit. A preview/query never calls this manager or overwrites a prior instance. */
export function createReportInstanceManager(store: ReportInstanceStore, options: { maxSnapshotBytes?: number } = {}) {
  const maxBytes = options.maxSnapshotBytes ?? 8_000_000;
  if (!Number.isSafeInteger(maxBytes) || maxBytes < 1) throw new ReportInstanceError("input", "实例快照字节预算应为正安全整数");
  return {
    read: store.read.bind(store), list: store.list.bind(store),
    save: async (input: Omit<ReportInstanceSnapshot, "revision">, options: { expectedRevision: number | null; signal?: AbortSignal }): Promise<ReportInstanceSnapshot> => {
      const expected = options.expectedRevision;
      if (expected !== null && (!Number.isSafeInteger(expected) || expected < 1 || expected >= Number.MAX_SAFE_INTEGER)) throw new ReportInstanceError("input", "实例预期修订无效");
      const safeInput = JSON.parse(plainSnapshot(input, maxBytes)) as Omit<ReportInstanceSnapshot, "revision">;
      const next = snapshotReportInstance({ ...safeInput, revision: (expected ?? 0) + 1 }, maxBytes);
      throwIfAborted(options.signal);
      if (!await store.compareAndSwap(next.scope, next.id, expected, next, options.signal)) throw new ReportInstanceError("conflict", "实例已存在或已变化，请显式确认修订后保存");
      return next;
    }
  };
}

/** Stable parameter identity without adding a database, user account or credential to the SDK. */
export function reportInstanceParameterKey(reportIds: string[], params: Record<string, string>): string {
  return serializeJobJson({ reportIds, params });
}
